/**
 * Builds the constellation dataset used by the Sky view.
 *
 *   node scripts/build-constellations.mjs [dir-with-d3-celestial-json]
 *
 * Source: d3-celestial by Olaf Frohn, https://github.com/ofrohn/d3-celestial
 * (BSD 3-Clause). Stick figures follow the IAU/Sky & Telescope style; borders
 * are the IAU constellation boundaries (J2000).
 *
 * Output:
 *   apps/web/public/data/constellations.json   figures + borders (fetched by the Sky view)
 *   apps/web/src/data/constellationNames.ts    names and label positions (bundled, used by search)
 */
import fs from "node:fs";
import path from "node:path";

const BASE = "https://raw.githubusercontent.com/ofrohn/d3-celestial/master/data/";
const FILES = ["constellations.json", "constellations.lines.json", "constellations.borders.json"];

async function load(name) {
  const local = process.argv[2] && path.join(process.argv[2], name);
  if (local && fs.existsSync(local)) return JSON.parse(fs.readFileSync(local, "utf8"));
  console.log("Downloading", BASE + name);
  const res = await fetch(BASE + name);
  if (!res.ok) throw new Error(`${name}: ${res.status}`);
  return res.json();
}

const [names, lines, borders] = await Promise.all(FILES.map(load));

/** RA in degrees (d3-celestial uses −180…180) → 0…360, rounded to save space. */
const ra = (v) => Math.round((((v % 360) + 360) % 360) * 1e4) / 1e4;
const dec = (v) => Math.round(v * 1e4) / 1e4;
const flat = (coords) => coords.flatMap(([a, d]) => [ra(a), dec(d)]);

const figures = {};
for (const f of lines.features) figures[f.id] = f.geometry.coordinates.map(flat);

const out = {
  source: "d3-celestial (Olaf Frohn), BSD 3-Clause — github.com/ofrohn/d3-celestial",
  figures,
  // ["And,Lac", [ra, dec, …]]: each boundary segment and the two constellations it separates.
  borders: borders.features.flatMap((f) => f.geometry.coordinates.map((c) => [f.ids, flat(c)])),
};
fs.writeFileSync(path.resolve("apps/web/public/data/constellations.json"), JSON.stringify(out));

const meta = names.features
  // Serpens is listed twice (Caput and Cauda); one label is enough.
  .filter((f, i, all) => all.findIndex((g) => g.id === f.id) === i)
  .map((f) => {
    const p = f.properties;
    return `  { id: "${f.id}", name: "${p.name}", genitive: "${p.gen}", meaning: "${p.en}", rank: ${Number(p.rank)}, ra: ${ra(f.geometry.coordinates[0])}, dec: ${dec(f.geometry.coordinates[1])} },`;
  });

fs.writeFileSync(
  path.resolve("apps/web/src/data/constellationNames.ts"),
  `/* Generated by scripts/build-constellations.mjs from d3-celestial (BSD 3-Clause). Do not edit. */

export interface ConstellationName {
  /** IAU three-letter abbreviation. */
  id: string;
  name: string;
  genitive: string;
  meaning: string;
  /** 1 = prominent, 3 = faint (label priority at wide fields of view). */
  rank: number;
  /** Label position, J2000 degrees. */
  ra: number;
  dec: number;
}

export const CONSTELLATION_NAMES: ConstellationName[] = [
${meta.join("\n")}
];
`,
);
console.log(`Wrote ${Object.keys(figures).length} figures, ${out.borders.length} border segments, ${meta.length} names.`);
